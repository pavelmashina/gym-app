import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dateTicks } from '../src/lib/statisticsDateTicks.js';
const read=p=>readFileSync(p,'utf8');
assert.deepEqual(dateTicks('2026-11-04','2026-11-04'),['2026-11-04']);
assert.deepEqual(dateTicks('2026-11-04','2026-11-05'),['2026-11-04','2026-11-05']);
assert.equal(dateTicks('2026-11-01','2026-11-03').length,3);
assert.equal(new Set(dateTicks('2026-01-01','2026-12-31')).size,8);
assert.deepEqual(dateTicks('','2026-11-04'),[]);
const sessions=read('src/lib/workoutSessions.js');
const report=read('src/components/WorkoutSessionScreenV3.jsx');
const detail=read('src/components/ProgramDetailScreen.jsx');
const chart=read('src/components/StatisticsInsights.jsx');
const catalog=read('src/components/CatalogProgramsPanel.jsx');
assert.match(sessions,/scheduledDate: workout\.scheduled_date,/);
assert.match(sessions,/completedDate: mode === 'completed'/);
assert.match(report,/entry\.workout\.completedDate \|\| entry\.workout\.scheduledDate/);
assert.match(report,/По плану: \{originallyScheduled\}/);
assert.match(report,/plannedSetLabel\(set, exercise\.prescription\)/);
assert.doesNotMatch(report, /exercise\.prescription && <p className="workout-exercise-prescription"/, 'No prescription line during an active session.');
assert.match(detail,/statusText=\{participationLabel\(participation\)\}/);
assert.doesNotMatch(detail,/className="program-detail-start-state"/);
assert.match(catalog,/<ProgramListCard/);
assert.match(catalog,/workoutCount/);
const receive=read('src/components/ReceiveProgramPanel.jsx');
const insights=read('src/components/StatisticsInsights.jsx');
assert.match(receive,/formatRussianCount\(preview\.workout_count/);
assert.match(receive,/formatRussianCount\(preview\.cycle_repeat_count/);
assert.match(receive,/formatRussianCount\(preview\.week_count/);
assert.match(insights,/formatRussianCount\(day\.count/);
