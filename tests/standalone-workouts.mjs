import {PGlite} from '@electric-sql/pglite';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {buildCatalogRelease} from '../scripts/exercise-catalog-release.mjs';
const read=p=>readFileSync(new URL(p,import.meta.url),'utf8');
const schema=JSON.parse(read('./fixtures/catalog-live-schema-20261015.json'));
const legacy=JSON.parse(read('../docs/exercise-catalog-v2/legacy-shared-catalog.json'));
const db=new PGlite();
const alice='00000000-0000-4000-8000-000000000001', bob='00000000-0000-4000-8000-000000000002';
const q=async(sql,args=[])=>(await db.query(sql,args)).rows;
const scalar=async(sql,args=[])=>(await q(sql,args))[0]?.value;
const login=async id=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);await db.exec('set role authenticated');};
const quote=s=>'"'+s.replaceAll('"','""')+'"';
try {
  await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
    create schema auth;create schema private;create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    grant usage on schema public,auth to authenticated,anon,service_role;
    insert into auth.users values('${alice}'),('${bob}');`);
  for(const t of schema.tables)await db.exec(t.ddl);
  for(const c of [...schema.constraints].sort((a,b)=>Number(a.foreign)-Number(b.foreign)))await db.exec(c.sql);
  for(const sql of schema.indexes)await db.exec(sql);
  for(const f of schema.functions)await db.exec(f.sql);
  for(const sql of schema.triggers)await db.exec(sql);
  for(const p of schema.policies)await db.exec(`create policy ${quote(p.name)} on public.${quote(p.table)} as ${p.permissive} for ${p.cmd} to ${p.roles.map(quote).join(',')} ${p.qual?'using ('+p.qual+')':''} ${p.check?'with check ('+p.check+')':''}`);
  for(const t of schema.tables)if(t.rls)await db.exec(`alter table public.${quote(t.name)} enable row level security`);
  for(const g of schema.grants)await db.exec(`grant ${g.privilege} on public.${quote(g.table)} to ${quote(g.role)}`);
  for(const e of legacy)await db.query('insert into exercises(id,name,muscle_group,exercise_type,movement_type,technique,equipment) values($1,$2,$3,$4,$5,$6,$7)',[e.id,e.name,e.muscle_group,e.exercise_type,e.movement_type,e.technique,e.equipment]);
  await db.exec(buildCatalogRelease({publish:true}));
  await db.exec(read('../supabase/migrations/20261015115110_standalone_workouts.sql'));
  await login(alice);
  const exercise=await scalar("select id value from exercise_catalog_v2 where measurement_type='weight_reps' and laterality='bilateral' limit 1");
  const payload={name:'Unchanged program',week_count:1,weeks:[{workouts:[{name:'Program day',exercises:[{exercise_id:exercise,name:'Exercise',sets:[{reps:8}]}]}]}]};
  const program=await scalar('select create_program_with_schedule($1::jsonb) value',[JSON.stringify(payload)]);
  const participation=await scalar('select start_program($1,current_date) value',[program]);
  const programDay=await scalar('select id value from scheduled_workouts where user_program_id=$1',[participation]);
  const snapshot=async()=>({programs:await q('select * from user_programs'),days:await q('select * from scheduled_workouts where user_program_id is not null'),exercises:await q('select * from scheduled_workout_exercises'),sets:await q('select * from scheduled_sets')});
  const before=await snapshot();
  const scheduled=await scalar('select start_standalone_workout() value');
  assert.equal(await scalar('select start_standalone_workout() value'),scheduled,'retry must reuse active session');
  const session=await scalar('select id value from workout_sessions where scheduled_workout_id=$1',[scheduled]);
  assert.equal(await scalar('select count(*)::int value from workout_session_exercises where workout_session_id=$1',[session]),0);
  await assert.rejects(q('select start_workout($1)',[programDay]));
  const a=await scalar('select add_standalone_exercise($1,$2) value',[session,exercise]);
  const b=await scalar('select add_standalone_exercise($1,$2) value',[session,exercise]);
  assert.equal(await scalar('select count(*)::int value from performed_sets'),0,'no copied sets');
  const contract=(await q('select measurement_type,load_mode,laterality from exercises where id=$1',[exercise]))[0];
  const result={metric_version:'v2',exercise_id:exercise,...contract,weight_unit:'kg',configuration_key:'standard',set_type:'working',completed:true,weight:25,reps:8};
  await q("insert into performed_sets(workout_session_exercise_id,set_number,set_type,completed,result_v2) values($1,1,'working',true,$2)",[a,JSON.stringify(result)]);
  await q('select reorder_workout_session_exercises($1,$2::uuid[])',[session,[b,a]]);
  await assert.rejects(q("select reorder_workout_session_exercises($1,$2::uuid[],'program')",[session,[a,b]]));
  await q('select pause_workout($1)',[scheduled]);
  await assert.rejects(q('select add_standalone_exercise($1,$2)',[session,exercise]));
  assert.equal(await scalar('select start_standalone_workout() value'),scheduled);
  await q('select resume_workout($1)',[scheduled]);
  await login(bob);
  assert.equal(await scalar('select count(*)::int value from workout_sessions'),0);
  assert.equal(await scalar('select count(*)::int value from scheduled_workouts'),0);
  await assert.rejects(q('select add_standalone_exercise($1,$2)',[session,exercise]));
  await assert.rejects(q('select complete_workout($1)',[session]));
  assert.equal((await q('update scheduled_workouts set standalone_owner_id=$1 where id=$2 returning id',[bob,scheduled])).length,0);
  const bobDay=await scalar('select start_standalone_workout() value'); // no program required
  await q('select abandon_workout(id) from workout_sessions where scheduled_workout_id=$1',[bobDay]);
  await login(alice);
  await q('select complete_workout($1)',[session]);
  assert.equal(await scalar("select count(*)::int value from workout_sessions where status='completed'"),1,'statistics includes standalone completion');
  assert.deepEqual(await snapshot(),before,'program and schedule must remain byte-for-byte unchanged');
  const next=await scalar('select start_standalone_workout() value');
  assert.notEqual(next,scheduled,'next workout starts from zero');
  await q('select abandon_workout(id) from workout_sessions where scheduled_workout_id=$1',[next]);
  assert.deepEqual(await snapshot(),before);
  const plannedSession=await scalar('select start_workout($1) value',[programDay]);
  await assert.rejects(q('select start_standalone_workout()'));
  await q('select complete_workout($1)',[plannedSession]);
  assert.equal(await scalar('select status value from user_programs where id=$1',[participation]),'completed');
  await db.exec('reset role;set role anon');
  await assert.rejects(q('select start_standalone_workout()'),e=>e.code==='42501');
  const home=read('../src/components/HomeScreen.jsx'), active=read('../src/components/WorkoutSessionScreenV3.jsx');
  assert(home.includes('<StandaloneWorkoutLauncher onOpenWorkout={onOpenWorkout}'));
  assert(active.includes('<StandaloneExerciseEditor sessionId={session.id}'));
  assert(active.includes('<ReorderExerciseScreen standalone={workout.standalone}'));
  assert(read('../src/lib/statistics.js').includes(".eq('status', 'completed')"));
  console.log('Standalone workouts passed: empty start, retry, add/results, pause/resume, reorder, statistics, program isolation, no-program user, RLS and planned regression.');
} finally {await db.close();}
