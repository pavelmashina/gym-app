import assert from 'node:assert/strict';
import { readFileSync,existsSync } from 'node:fs';
const read=p=>readFileSync(p,'utf8');
const catalog=read('src/lib/catalogPrograms.js');
const ui=read('src/components/CatalogProgramsPanel.jsx');
const css=read('src/catalog-programs-polish.css');
assert.match(catalog,/\.eq\('published', true\)/);
assert.equal(catalog.match(/\.eq\('published', true\)/g).length,2);
assert.match(catalog,/sourcePayload = row\.source_payload/);
assert.match(catalog,/import\.meta\.env\.BASE_URL/);
assert.match(catalog,/coverUrl,/);
assert.match(ui,/catalog-program-cover-image/);
assert.match(ui,/<ProgramOverviewIntro program=\{program\} coverUrl=\{program\.coverDetailUrl \|\| program\.coverUrl\} \/>/);
assert.match(ui,/function CatalogProgramFacts/);
assert.match(ui,/<CatalogProgramFacts details=\{program\.sourcePayload\?\.details\} \/>/);
assert.match(ui,/['"]Время тренировки['"]/);
assert.match(ui,/['"]Прогрессия['"]/);
assert.match(css,/\.catalog-program-cover-image img/);
assert.match(css,/object-fit:cover/);
assert.ok(existsSync('public/assets/fitness-club-banner.webp'),'Showcase cover must exist locally');
console.log('Showcase catalog cover, complete details and published-only access verified.');
