import assert from 'node:assert/strict';
import { readFileSync,existsSync } from 'node:fs';
const read=p=>readFileSync(p,'utf8');
const catalog=read('src/lib/catalogPrograms.js');
const ui=read('src/components/CatalogProgramsPanel.jsx');
const css=read('src/catalog-programs-polish.css');
assert.match(catalog,/\.eq\('published', true\)/);
assert.equal(catalog.match(/\.eq\('published', true\)/g).length,2);
assert.match(catalog,/sourcePayload = row\.source_payload/);
assert.match(catalog,/import\.meta\.env\.BASE_URL/);
assert.match(catalog,/coverUrl,/);
assert.match(ui,/catalog-program-cover-image/);
assert.match(ui,/<ProgramOverviewIntro program=\{program\} coverUrl=\{program\.coverDetailUrl \|\| program\.coverUrl\} \/>/);
assert.doesNotMatch(ui,/function CatalogProgramFacts/);
assert.doesNotMatch(ui,/<CatalogProgramFacts/);
const shared = read('src/components/ProgramOverview.jsx');
assert.match(shared,/\['Продолжительность', details\.duration\]/);
assert.match(shared,/\['Частота', details\.frequency\]/);
assert.doesNotMatch(shared,/\['Время тренировки', details\.estimated_time\]/);
assert.doesNotMatch(shared,/\['Прогрессия', details\.progression\]/);
assert.doesNotMatch(ui,/catalog-program-card-arrow/);
assert.match(ui,/catalog-program-difficulty level-\$\{difficulty\}/);
assert.doesNotMatch(ui,/Исходные упражнения, подходы и повторения/);
assert.match(css,/\.catalog-program-cover-image img/);
assert.match(css,/object-fit:cover/);
assert.ok(existsSync('public/assets/program-fullbody-example-hq.webp'),'High-resolution catalog cover must exist locally');
console.log('Showcase catalog cover, complete details and published-only access verified.');
