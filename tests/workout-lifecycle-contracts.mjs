import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = (p) => fs.readFileSync(p, 'utf8');
const home = read('src/components/HomeScreen.jsx');
const detail = read('src/components/ProgramDetailScreen.jsx');
const sessions = read('src/lib/workoutSessions.js');
const lifecycle = read('supabase/schema/workout-session-lifecycle.sql');
const statuses = read('supabase/schema/program-status-lifecycle.sql');
assert.match(home, /recoveryResponse[\s\S]*\.lt\('scheduled_date', dateKey\)/);
assert.match(home, /Перенести на сегодня/);
assert.match(home, /effectiveWorkout\.scheduledDate \|\| selectedDateKey/);
assert.doesNotMatch(home, /Выполнено<\/span>/);
assert.match(detail, /participation\.status === 'cancelled'/);
assert.doesNotMatch(detail, /participation\.status === 'abandoned'/);
assert.match(statuses, /active','paused','completed','cancelled/);
assert.match(lifecycle, /paused_at/);
assert.match(lifecycle, /active_duration_seconds/);
assert.match(lifecycle, /future/i);
assert.match(sessions, /set_type !== 'working'/);
assert.match(sessions, /\.eq\('status', 'completed'\)/);
console.log('Workout lifecycle contract tests passed.');
