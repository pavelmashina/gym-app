import assert from 'node:assert/strict';
import { parseMetricInput,validateResultV2,compareResultsV2,externalLoadVolumeV2 } from '../src/lib/exerciseResultsV2.js';
const base = {metric_version:'v2',exercise_id:'exercise',measurement_type:'weight_reps',load_mode:'barbell_total',
  weight_unit:'kg',configuration_key:'standard_v1',laterality:'bilateral',side:null,equipment_instance_id:null,
  set_type:'working',completed:true,weight:40,reps:10};
assert.deepEqual(validateResultV2(base),[]);
for(const value of ['','',null,undefined]) assert.equal(parseMetricInput(value),null);
assert.equal(parseMetricInput('12,5'),12.5);
assert.throws(()=>parseMetricInput('9'.repeat(400)));
for(const value of ['  ','12kg','1e3',true,NaN,Infinity]) assert.throws(()=>parseMetricInput(value));
assert.equal(compareResultsV2({...base,weight:50},base),1);
assert.equal(compareResultsV2({...base,weight:50,reps:8},base),null);
assert.equal(compareResultsV2({...base,metric_version:'legacy_v1'},base),null);
assert.equal(compareResultsV2({...base,set_type:'warmup'},base),null);
assert.equal(compareResultsV2({...base,configuration_key:'other'},base),null);
assert.equal(externalLoadVolumeV2(base).value,400);
assert.equal(externalLoadVolumeV2({...base,set_type:'warmup'}),null);
const timed={...base,measurement_type:'duration',load_mode:'bodyweight',weight:null,reps:null,duration_seconds:60};
assert.deepEqual(validateResultV2(timed),[]);
assert.equal(compareResultsV2({...timed,duration_seconds:90},timed),1);
assert.equal(externalLoadVolumeV2(timed),null);
assert(validateResultV2({...timed,duration_seconds:0}).includes('invalid:duration_seconds'));
assert(validateResultV2({...timed,reps:1}).includes('unexpected:reps'));
const assisted={...base,measurement_type:'assisted_reps',load_mode:'assistance',weight:null,assistance_weight:30,equipment_instance_id:'machine-a'};
assert.deepEqual(validateResultV2(assisted),[]);
assert.equal(compareResultsV2({...assisted,assistance_weight:40},assisted),-1);
assert.equal(compareResultsV2({...assisted,assistance_weight:20},assisted),1);
assert.equal(compareResultsV2({...assisted,equipment_instance_id:'machine-b'},assisted),null);
assert.equal(compareResultsV2({...assisted,equipment_instance_id:null},{...assisted,equipment_instance_id:null}),null);
assert.equal(externalLoadVolumeV2(assisted),null);
assert(validateResultV2({...assisted,weight:10}).includes('unexpected:weight'));
const bw={...base,measurement_type:'bodyweight_reps',load_mode:'bodyweight',weight:null};
assert.equal(compareResultsV2({...bw,reps:12},bw),1);
assert.equal(compareResultsV2({...bw,reps:12,weight:5},bw),null);
assert(validateResultV2({...base,laterality:'unilateral'}).includes('missing:side'));
assert.equal(compareResultsV2({...base,laterality:'unilateral',side:'left'},{...base,laterality:'unilateral',side:'right'}),null);
const carry={...base,measurement_type:'carry',load_mode:'dumbbell_each',reps:null,distance_meters:20};
assert.deepEqual(validateResultV2(carry),[]);
assert.equal(compareResultsV2({...carry,distance_meters:30},carry),1);
assert.equal(compareResultsV2({...carry,distance_meters:30,weight:50},carry),null);
assert.equal(compareResultsV2({...carry,distance_meters:null,duration_seconds:60},{...carry,duration_seconds:60}),null);
assert(validateResultV2({...carry,distance_meters:null}).includes('missing:carry_extent'));
const cardio={...base,measurement_type:'cardio',load_mode:'none',weight:null,reps:null,duration_seconds:300,distance_meters:1000};
assert.equal(compareResultsV2({...cardio,duration_seconds:280},cardio),1);
assert.equal(compareResultsV2({...cardio,distance_meters:1200},cardio),1);
assert.equal(compareResultsV2({...cardio,duration_seconds:280,distance_meters:800},cardio),null);
assert.deepEqual(validateResultV2({...base,completed:false,weight:null,reps:null}),[]);
assert(validateResultV2({...base,weight:NaN}).includes('invalid:weight'));
assert(validateResultV2({...base,reps:1.5}).includes('invalid:reps'));
console.log('Result v2 contracts: 6 formats, assistance direction, machine/side/config isolation, warmup and legacy exclusion passed.');
