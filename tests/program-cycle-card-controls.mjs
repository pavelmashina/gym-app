import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { CATEGORY_OPTIONS } from '../src/lib/programOptions.js';
import { formatProgramExerciseSummary } from '../src/lib/programExerciseSummary.js';
const read = path => readFileSync(path, 'utf8');
const catalog = read('src/components/CatalogProgramsPanel.jsx');
const owned = read('src/components/ProgramDetailScreen.jsx');
const workout = read('src/components/ProgramWorkoutBlock.jsx');
const programs = read('src/components/ExercisesScreen.jsx');
const intro = read('src/components/ProgramOverview.jsx');
const share = read('src/components/ShareProgramButton.jsx');
const css = read('src/november-card-navigation-refinements.css');

assert.equal(CATEGORY_OPTIONS.length, 5);
assert.match(catalog, /<ProgramWorkoutBlock/);
assert.match(owned, /<ProgramWorkoutBlock/);
assert.match(workout, /useState\(false\)/);
assert.match(workout, /aria-expanded=\{open\}/);
assert.doesNotMatch(workout, /Тренировка цикла/);
assert.match(workout, /catalog-workout-exercise-count/);
assert.doesNotMatch(owned, /<strong>Этап \{group\.number\}<\/strong>/);
assert.doesNotMatch(owned, /Выполненные тренировки/);
assert.match(owned, /program-schedule-timeline/);
assert.doesNotMatch(owned, /Редактирование структуры станет/);
assert.doesNotMatch(owned, /Редактирование недоступно/);
assert.match(owned, /\{canEditProgram && <button className="program-detail-edit-button"/);
assert.match(owned, /<TrashIcon \/>/);
assert.match(owned, /<PauseIcon \/>/);
assert.match(owned, /<ResumeIcon \/>/);
assert.match(owned, /<CloseProgramIcon \/>/);
assert.match(owned, /statusText=\{participationLabel\(participation\)\}/);
assert.doesNotMatch(owned, /Дата старта:/);
assert.match(intro, /className="program-detail-title-status"/);
assert.match(share, /aria-label="Поделиться программой"/);
assert.doesNotMatch(share, /<ShareIcon\s*\/> Поделиться программой/);
assert.match(programs, /className="my-programs-create-row"/);
assert.ok(programs.indexOf('className="my-programs-create-row"') < programs.indexOf('className="my-programs-switcher"'));
assert.match(programs, /className={`my-program-status-corner \$\{state.tone\}`}/);
assert.match(programs, /<CheckIcon \/> : <PlayIcon \/>/);
assert.doesNotMatch(programs, /className="my-program-inline-status"/);
assert.doesNotMatch(programs, /className="my-program-arrow"/);
assert.match(programs, /className="training-toolbar-row compact-training-toolbar my-programs-create-row"/);
assert.match(css, /text-align: justify/);
assert.match(css, /\.program-detail-phone \.program-participation-action svg/);
assert.equal(formatProgramExerciseSummary({prescription:'3×10. Отдых 30 сек'}),'3 подхода по 10 раз · отдых 30 сек');
assert.equal(formatProgramExerciseSummary({prescription:'3×10. Отдых 90 сек'}),'3 подхода по 10 раз · отдых 1:30 мин');
assert.equal(formatProgramExerciseSummary({prescription:'3×10. Отдых 105 сек'}),'3 подхода по 10 раз · отдых 1:45 мин');
console.log('Program cycle cards, icon-only actions, inline statuses and rest formatting verified.');
